package tools

import (
	"context"
	"encoding/json"

	"curated-backend/internal/agent/core"
	"curated-backend/internal/contracts"
)

const UpdateBookMetadataName = "update_book_metadata"

type BookMetadataWriter interface {
	GetBookMetadataState(context.Context, string, string) (contracts.BookMetadataState, error)
	ApplyBookMetadata(context.Context, string, string, contracts.BookMetadata, string) (contracts.BookMetadataState, error)
}

type BookMetadataArgs struct {
	Kind     string                 `json:"kind"`
	ID       string                 `json:"id"`
	Metadata contracts.BookMetadata `json:"metadata"`
	// Snapshot is supplied by the Action before the model call, preventing stale inference.
	Snapshot string `json:"snapshot"`
}

func RegisterBookMetadataTool(reg *core.Registry, w BookMetadataWriter) error {
	credit := object(map[string]core.Schema{"name": strField("Source name"), "evidence": strField("Exact source fragment")}, "name", "evidence")
	roles := core.Schema{Type: "array", Items: &credit, MaxItems: 12}
	metadata := object(map[string]core.Schema{
		"cleanTitle": strField("Original main title"), "translatedTitle": strField("Translated main title"),
		"authors": roles, "circles": roles, "models": roles, "photographers": roles, "uncertainty": strField("Unresolved roles"),
	}, "cleanTitle", "translatedTitle")
	schema := object(map[string]core.Schema{"kind": {Type: "string", Enum: []string{"comic", "photo"}}, "id": strField("Book id"), "metadata": metadata, "snapshot": strField("Source snapshot")}, "kind", "id", "metadata", "snapshot")
	return reg.Register(core.ToolDefinition{
		Name: UpdateBookMetadataName, Description: "Confirm title and source-backed credits generated by the book metadata Action.", ParamsSchema: schema,
		Permission: core.PermissionWritePreview, Domain: core.DomainUserWrite,
		Handler: func(ctx context.Context, call core.Call) (core.Result, error) {
			if call.Channel != core.ChannelAction {
				return core.Result{Error: &core.ToolError{Code: "AI_TOOL_INVALID_ARGS", Message: "Use the book metadata Action"}}, nil
			}
			var args BookMetadataArgs
			if err := json.Unmarshal(call.Args, &args); err != nil {
				return core.Result{}, err
			}
			state, err := w.GetBookMetadataState(ctx, args.Kind, args.ID)
			if err != nil {
				return bookWriteError(err, args.Kind == "comic"), nil
			}
			before, _ := json.Marshal(state)
			if string(before) != args.Snapshot {
				return conflictResult(), nil
			}
			if err := contracts.ValidateBookMetadata(args.Kind, args.Metadata, state); err != nil {
				return core.Result{Error: &core.ToolError{Code: "AI_TOOL_INVALID_ARGS", Message: err.Error()}}, nil
			}
			after, _ := json.Marshal(args.Metadata)
			old, _ := json.Marshal(state.Metadata)
			if string(after) == string(old) && state.Title == args.Metadata.TranslatedTitle {
				return core.Result{OK: true}, nil
			}
			return core.Result{OK: true, Preconditions: []core.Change{{Path: "book.snapshot", Before: string(before)}}, Changes: []core.Change{{Path: "title", Before: state.Title, After: args.Metadata.TranslatedTitle}, {Path: "metadata", Before: state.Metadata, After: args.Metadata}}}, nil
		},
		Apply: func(ctx context.Context, call core.Call) (core.Result, error) {
			var args BookMetadataArgs
			if err := json.Unmarshal(call.Args, &args); err != nil {
				return core.Result{}, err
			}
			before, ok := previewBefore(call, "book.snapshot")
			if !ok {
				return conflictResult(), nil
			}
			state, err := w.ApplyBookMetadata(ctx, args.Kind, args.ID, args.Metadata, before)
			if err != nil {
				return bookWriteError(err, args.Kind == "comic"), nil
			}
			return core.Result{OK: true, Data: state}, nil
		},
	})
}
