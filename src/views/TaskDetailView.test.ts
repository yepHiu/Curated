import { flushPromises, mount } from "@vue/test-utils"
import { ref } from "vue"
import { createMemoryHistory, createRouter } from "vue-router"
import { beforeEach, describe, expect, it, vi } from "vitest"
import { i18n } from "@/i18n"
import TaskDetailView from "./TaskDetailView.vue"
import TaskDetailContent from "@/components/jav-library/TaskDetailContent.vue"
import { projectSubtitle, projectOrganization, summarizeTasks } from "@/lib/task-center"
const api = vi.hoisted(() => ({ get: vi.fn(), action: vi.fn(), refresh: vi.fn(), reloadMoviesFromApi: vi.fn(), getTagOrganizationItems: vi.fn() }))
const revision = ref(0)
vi.mock("@/services/task-center-service", () => ({ useTaskCenterService: () => api }))
vi.mock("@/composables/use-task-center", () => ({ useTaskCenter: () => ({ revision, refresh: api.refresh }) }))
vi.mock("@/composables/use-tag-organization", () => ({ useTagOrganization: () => api, organizationErrorText: (s: string) => s }))
vi.mock("@/composables/use-subtitle-jobs", () => ({ useSubtitleJobs: () => api }))
vi.mock("@/services/library-service", () => ({ useLibraryService: () => api }))
vi.mock("@/services/ai-service", () => ({ useAIService: () => api }))
vi.mock("@/services/subtitle-service", () => ({ useSubtitleService: () => ({}) }))
vi.mock("@/lib/experimental-agent", () => ({ useExperimentalAgent: () => ({ writeEnabled: ref(true) }) }))
vi.mock("@/components/ui/dialog", () => ({ Dialog: { props: ["open"], template: '<section v-if="open" role="dialog"><slot /></section>' }, ...Object.fromEntries(["DialogContent", "DialogHeader", "DialogTitle", "DialogDescription", "DialogFooter"].map(name => [name, { template: '<div><slot /></div>' }])) }))
vi.mock("@/components/jav-library/TaskProcessingItem.vue", () => ({ default: { props: ["title", "status"], template: '<button data-processing-item>{{ title }} {{ status }}</button>' } }))
const job = projectSubtitle({ id: "a", movieId: "movie", fileId: "file", fileName: "part.mp4", state: "running", stage: "translating", completed: 8, total: 12, assets: [], createdAt: "2026-10-17T00:00:00Z", updatedAt: "2026-10-17T00:01:00Z", translationModel: "qwen-flash" })
async function setup() {
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: "/tasks/:taskKey", component: TaskDetailView }, { path: "/tasks", component: { template: '<div />' } }, { path: "/detail/:id", name: "detail", component: { template: '<div />' } }] })
  await router.push("/tasks/subtitle:a")
  const wrapper = mount(TaskDetailView, { global: { plugins: [router, i18n] } }); await flushPromises()
  return { wrapper, router }
}
beforeEach(() => { vi.clearAllMocks(); i18n.global.locale.value = "zh-CN"; api.get.mockResolvedValue(structuredClone(job)); api.getTagOrganizationItems.mockResolvedValue([]) })
describe("task detail behavior", () => {
  it("keeps superseded failures in history with a replacement link and no retry actions", async () => {
    const old = { ...job, state: "failed" as const, subtitle: { ...job.subtitle!, state: "failed", supersededBy: "new" } }
    api.get.mockResolvedValue(old)
    const { wrapper } = await setup()
    const summary = summarizeTasks([old, job])
    expect(summary.attention).toBe(0)
    expect(summary.history).toBe(1)
    expect(summary.running).toBe(1)
    expect(wrapper.text()).toContain("此失败记录已由重新执行的任务接替")
    expect(wrapper.findAll("a").some(a => a.attributes("href") === "/tasks/subtitle%3Anew")).toBe(true)
    expect(wrapper.findAll("button").some(b => ["重试未完成部分", "重新执行整个任务"].includes(b.text()))).toBe(false)
    wrapper.unmount()
  })
  it("keeps shared dialog content on the same task after a full restart", async () => {
    api.get.mockResolvedValue({ ...job, state: "failed" })
    const wrapper = mount(TaskDetailContent, { props: { taskKey: "subtitle:a" }, global: { plugins: [i18n], stubs: { RouterLink: true } } })
    await flushPromises()
    await wrapper.findAll("button").find(b => b.text() === "重新执行整个任务")!.trigger("click")
    api.action.mockResolvedValueOnce(undefined)
    api.get.mockResolvedValue({ ...job, state: "queued", stage: "preparing", completed: 0 })
    await wrapper.get('[role="dialog"]').findAll("button").find(b => b.text() === "确认")!.trigger("click")
    await flushPromises()
    expect(wrapper.props("taskKey")).toBe("subtitle:a")
    expect(wrapper.emitted("restarted")).toBeUndefined()
    expect(api.get).toHaveBeenLastCalledWith("subtitle:a")
    expect(wrapper.findAll("button").some(b => b.text() === "重新执行整个任务")).toBe(false)
    wrapper.unmount()
  })
  it("offers both retry modes and confirms a full restart without changing the task ID", async () => {
    api.get.mockResolvedValue({ ...job, state: "failed" })
    const { wrapper, router } = await setup()
    expect(wrapper.findAll("button").some(b => b.text() === "重试未完成部分")).toBe(true)
    const restart = wrapper.findAll("button").find(b => b.text() === "重新执行整个任务")!
    await restart.trigger("click")
    expect(api.action).not.toHaveBeenCalled()
    expect(wrapper.get('[role="dialog"]').text()).toContain("任务编号保持不变")
    expect(wrapper.get('[role="dialog"]').text()).toContain("不复用旧检查点")
    expect(wrapper.get('[role="dialog"]').text()).toContain("费用")
    api.action.mockResolvedValueOnce(undefined)
    api.get.mockResolvedValue({ ...job, state: "queued", stage: "preparing", completed: 0 })
    await wrapper.get('[role="dialog"]').findAll("button").find(b => b.text() === "确认")!.trigger("click")
    await flushPromises()
    expect(api.action).toHaveBeenCalledWith(expect.objectContaining({ key: "subtitle:a" }), "restart")
    expect(api.get).toHaveBeenCalledWith("subtitle:a")
    expect(router.currentRoute.value.params.taskKey).toBe("subtitle:a")
    wrapper.unmount()
  })
  it("allows a full restart after checkpoint expiry but disables it for remote connections", async () => {
    api.get.mockResolvedValue({ ...job, state: "failed", subtitle: { ...job.subtitle!, expiresAt: "2020-01-01T00:00:00Z" } })
    const { wrapper } = await setup()
    expect(wrapper.findAll("button").some(b => b.text() === "重试未完成部分")).toBe(false)
    expect(wrapper.findAll("button").find(b => b.text() === "重新执行整个任务")!.attributes("disabled")).toBeUndefined()
    api.get.mockResolvedValue({ ...job, state: "failed", canManage: false })
    revision.value++; await flushPromises()
    expect(wrapper.findAll("button").find(b => b.text() === "重新执行整个任务")!.attributes("disabled")).toBeDefined()
    wrapper.unmount()
  })
  it("keeps the failed task and reports a full-restart error without switching task", async () => {
    api.get.mockResolvedValue({ ...job, state: "failed" })
    const { wrapper, router } = await setup()
    await wrapper.findAll("button").find(b => b.text() === "重新执行整个任务")!.trigger("click")
    api.action.mockRejectedValueOnce(new Error("subtitle queue is full"))
    await wrapper.get('[role="dialog"]').findAll("button").find(b => b.text() === "确认")!.trigger("click")
    await flushPromises()
    expect(wrapper.get('[role="dialog"]').text()).toContain("subtitle queue is full")
    expect(router.currentRoute.value.params.taskKey).toBe("subtitle:a")
    wrapper.unmount()
  })
  it("shows persisted provider diagnostics as text on failed subtitle tasks", async () => {
    const providerError = 'HTTP 400: {"code":"DataInspectionFailed","message":"<script>alert(1)</script>","request_id":"req-123"}'
    api.get.mockResolvedValue({ ...job, state: "failed", subtitle: { ...job.subtitle!, providerError } })
    const { wrapper } = await setup()
    expect(wrapper.find("pre").text()).toBe(providerError)
    expect(wrapper.find("script").exists()).toBe(false)
    wrapper.unmount()
  })
  it("moves the active stage from loading to success or error and stops on disconnect", async () => {
    const { wrapper } = await setup()
    const states = () => wrapper.findAll('[data-node-state]').map(n => n.attributes('data-node-state'))
    expect(states()).toEqual(["success", "success", "running", "pending"])
    api.get.mockResolvedValue({ ...job, state: "failed" }); revision.value++; await flushPromises()
    expect(states()).toEqual(["success", "success", "error", "pending"])
    api.get.mockResolvedValue({ ...job, stage: "uploading" }); revision.value++; await flushPromises()
    expect(states()).toEqual(["success", "running", "pending", "pending"])
    api.get.mockRejectedValueOnce(new Error("offline")); revision.value++; await flushPromises()
    expect(states()).toEqual(["success", "paused", "pending", "pending"])
    api.get.mockResolvedValue({ ...job, state: "cancelled" }); revision.value++; await flushPromises()
    expect(states()).toEqual(["success", "success", "paused", "pending"])
    api.get.mockResolvedValue({ ...job, state: "succeeded", stage: "done" }); revision.value++; await flushPromises()
    expect(states()).toEqual(["success", "success", "success", "success"])
    wrapper.unmount()
  })
  it("requires confirmation before cancellation and respects a read-only connection", async () => {
    const { wrapper } = await setup()
    const cancel = wrapper.findAll("button").find(b => b.text() === "取消任务")!
    await cancel.trigger("click"); expect(api.action).not.toHaveBeenCalled()
    await wrapper.find('[role="dialog"]').findAll("button").find(b => b.text() === "确认")!.trigger("click")
    await flushPromises(); expect(api.action).toHaveBeenCalledWith(expect.objectContaining({ key: "subtitle:a" }), "cancel")
    api.get.mockResolvedValue({ ...job, canManage: false }); revision.value++; await flushPromises()
    expect(wrapper.findAll("button").find(b => b.text() === "取消任务")!.attributes("disabled")).toBeDefined()
    wrapper.unmount()
  })
  it("keeps progress on network failure and discards late details after navigating", async () => {
    const { wrapper, router } = await setup()
    api.get.mockRejectedValueOnce(new Error("offline")); revision.value++; await flushPromises()
    expect(wrapper.text()).toContain("part.mp4")
    expect(wrapper.text()).toContain("最近状态")
    expect(wrapper.findAll("button").find(b => b.text() === "取消任务")!.attributes("disabled")).toBeDefined()
    let finish!: (v: typeof job) => void
    api.get.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
    revision.value++; await flushPromises()
    api.get.mockResolvedValue({ ...job, key: "subtitle:b", id: "b", subtitle: { ...job.subtitle!, fileName: "other.mp4" } })
    await router.push("/tasks/subtitle:b"); await flushPromises()
    finish(job); await flushPromises()
    expect(wrapper.text()).toContain("other.mp4"); expect(wrapper.text()).not.toContain("part.mp4")
    wrapper.unmount()
  })
})

const organization = projectOrganization({ id: "org", taskId: "org", status: "completed", stage: "done", triggerReason: "selected", total: 51, processed: 51, succeeded: 50, unresolved: 0, failed: 1, revision: 1, createdAt: "", updatedAt: "" })
const organizationRows = Array.from({ length: 51 }, (_, i) => ({ movieId: `movie-${i}`, title: `Title ${i}`, status: i === 26 ? "failed" : "succeeded", reason: "Detailed reason", evidence: [], translations: [] }))

it("replaces movie item pages, refreshes the current page and retains it on failure", async () => {
  api.get.mockResolvedValue(organization)
  api.getTagOrganizationItems.mockImplementation(async (_id: string, offset = 0) => organizationRows.slice(offset, offset + 25))
  const { wrapper } = await setup()
  const next = () => wrapper.get('[data-items-pagination]').findAll('button')[1]!
  const previous = () => wrapper.get('[data-items-pagination]').findAll('button')[0]!
  expect(wrapper.findAll('[data-processing-item]')).toHaveLength(25)
  expect(wrapper.text()).not.toContain("Detailed reason")
  expect(previous().attributes('disabled')).toBeDefined()
  await next().trigger('click'); await flushPromises()
  expect(api.getTagOrganizationItems).toHaveBeenLastCalledWith('org', 25)
  expect(wrapper.findAll('[data-processing-item]')).toHaveLength(25)
  expect(wrapper.findAll('[data-processing-item]')[0]!.text()).toContain('Title 25')
  api.get.mockResolvedValue({ ...organization, organization: { ...organization.organization!, revision: 2 } })
  revision.value++; await flushPromises()
  expect(api.getTagOrganizationItems).toHaveBeenLastCalledWith('org', 25)
  await wrapper.findAll('button').find(b => b.text() === '只看本页问题')!.trigger('click')
  expect(wrapper.findAll('[data-processing-item]')).toHaveLength(1)
  expect(wrapper.find('[data-processing-item]').text()).toContain('Title 26')
  api.getTagOrganizationItems.mockRejectedValueOnce(new Error('offline'))
  await next().trigger('click'); await flushPromises()
  expect(wrapper.get('[data-items-pagination]').text()).toContain('2 / 3')
  expect(wrapper.find('[data-processing-item]').text()).toContain('Title 26')
  await wrapper.findAll('button').find(b => b.text() === '显示本页全部')!.trigger('click')
  await next().trigger('click'); await flushPromises()
  expect(wrapper.findAll('[data-processing-item]')).toHaveLength(1)
  expect(next().attributes('disabled')).toBeDefined()
  await previous().trigger('click'); await flushPromises()
  expect(wrapper.findAll('[data-processing-item]')).toHaveLength(25)
  wrapper.unmount()
})

it("ignores a late movie item page after switching tasks", async () => {
  api.get.mockResolvedValue(organization)
  api.getTagOrganizationItems.mockResolvedValue(organizationRows.slice(0, 25))
  const { wrapper, router } = await setup()
  let finish!: (rows: typeof organizationRows) => void
  api.getTagOrganizationItems.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
  await wrapper.get('[data-items-pagination]').findAll('button')[1]!.trigger('click')
  api.get.mockResolvedValue({ ...organization, key: 'organize:other', id: 'other', organization: { ...organization.organization!, id: 'other', total: 1 } })
  api.getTagOrganizationItems.mockResolvedValue([{ ...organizationRows[0], title: 'Other task' }])
  await router.push('/tasks/organize:other'); await flushPromises()
  finish(organizationRows.slice(25, 50)); await flushPromises()
  expect(wrapper.findAll('[data-processing-item]')).toHaveLength(1)
  expect(wrapper.text()).toContain('Other task')
  expect(wrapper.text()).not.toContain('Title 25')
  wrapper.unmount()
})
